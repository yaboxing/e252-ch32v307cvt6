EMCY_GENERIC = {
    0x0000: "无错误（信息性消息）",
    0x1000: "通用错误",
    0x2000: "电流错误",
    0x3000: "电压错误",
    0x4000: "温度错误",
    0x5000: "设备硬件错误",
    0x6000: "设备软件错误",
    0x7000: "附加模块错误",
    0x8000: "监控错误",
    0x9000: "外部错误",
    0xF000: "附加功能错误",
}


def explain_al(code: int) -> dict:
    name, detail = AL_CODES.get(code, ("未知状态码", "未收录的 AL 状态码，请参考 ETG.1020。"))
    return {"code": code, "name": name, "detail": detail}


def explain_emcy(code: int) -> str:
    base = EMCY_GENERIC.get(code & 0xF000)
    if code == 0:
        return EMCY_GENERIC[0]
    return base or "厂商自定义错误码，请参考设备 EMCY 列表/ETG.1020。"
